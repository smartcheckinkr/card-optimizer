/** 네트워크 등급별 혜택 묶음 */
export function networkPerksFor(network: Card['network'], tier?: string): Perk[] {
  if (network === 'AMEX') {
    if (!tier || /platinum|플래티넘|플래티늄/i.test(tier)) return AMEX_PLATINUM_PERKS;
    return [];
  }
  if (network === 'VISA') {
    if (tier && /infinite|인피니트/i.test(tier)) return VISA_INFINITE_PERKS;
    if (tier && /signature|시그니처/i.test(tier)) return VISA_SIGNATURE_PERKS;
    return [];
  }
  if (network === 'MASTERCARD') {
    if (tier && /world|월드/i.test(tier) && !/elite|엘리트/i.test(tier)) return MASTERCARD_WORLD_PERKS;
    if (tier && /elite|엘리트|world|월드/i.test(tier)) return MASTERCARD_WORLD_PERKS;
    if (tier && /platinum|titanium|diamond|플래티넘|티타늄|다이아몬드/i.test(tier)) {
      return MASTERCARD_PLATINUM_PERKS;
    }
    return [];
  }
  return [];
}

