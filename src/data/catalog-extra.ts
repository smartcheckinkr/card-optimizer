function perf(options: {
  prevThreshold: number;
  thresholdScope?: string;
  minPerTransaction?: number;
  excludedCategories?: CategoryId[];
  excludedKeywords?: string[];
}): PerformanceRule {
  return {
    prevThreshold: options.prevThreshold,
    thresholdScope: options.thresholdScope,
    minPerTransaction: options.minPerTransaction ?? 0,
    excludedCategories: options.excludedCategories ?? [],
    excludedKeywords: options.excludedKeywords ?? [],
    conditions: [
      {
        label: options.thresholdScope ?? '기본 혜택',
        amount: options.prevThreshold,
        note: options.prevThreshold > 0 ? '전월 이용금액 기준' : '전월 실적 조건 없음',
      },
    ],
  };
}

function benefit(options: BenefitRule): BenefitRule {
  return options;
}

function perk(options: Omit<Perk, 'layer' | 'provider'> & { provider?: string; layer?: Perk['layer'] }): Perk {
  return {
    layer: options.layer ?? 'card',
    provider: options.provider ?? '카드사',
    ...options,
  } as Perk;
}

